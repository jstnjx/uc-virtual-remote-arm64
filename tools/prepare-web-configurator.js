#!/usr/bin/env node
import crypto from "node:crypto";
import fs from "node:fs";
import fsp from "node:fs/promises";
import os from "node:os";
import path from "node:path";
import { spawnSync } from "node:child_process";
import { fileURLToPath } from "node:url";

const VERSION = "2.3.3-unfoldedtools.8";
const SOURCE_DIRECTORY_NAME = `web-configurator-${VERSION}`;
const SOURCE_ARCHIVE_NAME = `${SOURCE_DIRECTORY_NAME}-source.tar.gz`;
const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const sourceDir = path.resolve(
  process.env.UCVR_WEB_CONFIGURATOR_SOURCE_DIR || path.join(root, "web-configurator")
);
const outputDir = path.resolve(
  process.env.UCVR_WEB_CONFIGURATOR_DIR || path.join(root, "web-configurator-build")
);
const sourceOutputDir = path.resolve(
  process.env.UCVR_WEB_CONFIGURATOR_SOURCE_OUTPUT_DIR || path.join(root, "web-configurator-source")
);
const sourceArchive = path.join(sourceOutputDir, SOURCE_ARCHIVE_NAME);
const markerFile = path.join(outputDir, ".source-tree-sha256");
const force = process.argv.includes("--force");

function fail(message) {
  console.error(`[web-configurator] ${message}`);
  process.exit(1);
}

function sha256(data) {
  return crypto.createHash("sha256").update(data).digest("hex");
}

function run(command, args, cwd, env = {}) {
  console.log(`> ${command} ${args.join(" ")}`);
  const executable = process.platform === "win32" && command === "npm" ? "npm.cmd" : command;
  const result = spawnSync(executable, args, {
    cwd,
    env: { ...process.env, ...env },
    stdio: "inherit",
    windowsHide: true
  });
  if (result.error) fail(result.error.message);
  if (result.status !== 0) fail(`${command} exited with status ${result.status}`);
}

function walkFiles(directory) {
  const result = [];
  const stack = [""];
  while (stack.length) {
    const relative = stack.pop();
    const current = path.join(directory, relative);
    for (const entry of fs.readdirSync(current, { withFileTypes: true })) {
      if (entry.name === "node_modules" || entry.name === "dist") continue;
      const child = path.join(relative, entry.name);
      if (entry.isDirectory()) stack.push(child);
      else if (entry.isFile()) result.push(child.split(path.sep).join("/"));
    }
  }
  return result.sort();
}

function sourceTreeSha256() {
  const digest = crypto.createHash("sha256");
  for (const relative of walkFiles(sourceDir)) {
    digest.update(relative);
    digest.update("\0");
    digest.update(fs.readFileSync(path.join(sourceDir, relative)));
    digest.update("\0");
  }
  return digest.digest("hex");
}

function validateSource() {
  const packageFile = path.join(sourceDir, "package.json");
  const lockFile = path.join(sourceDir, "package-lock.json");
  if (!fs.existsSync(packageFile) || !fs.existsSync(lockFile)) {
    fail(`committed Web Configurator source is missing from ${sourceDir}`);
  }
  const pkg = JSON.parse(fs.readFileSync(packageFile, "utf8"));
  if (pkg.version !== VERSION || pkg.license !== "GPL-3.0-only") {
    fail("committed Web Configurator source metadata is incorrect");
  }
  if (pkg.dependencies?.["@fortawesome/fontawesome-free"] || pkg.devDependencies?.["@fortawesome/fontawesome-free"]) {
    fail("Font Awesome dependency remains in the committed source");
  }
  for (const relative of [
    "ARTWORK.md",
    "MODIFICATIONS.md",
    "LICENSE",
    "LICENSES/CC-BY-4.0.txt",
    "src/main.ts",
    "public/images/remote-3-dark-front.webp",
    "public/images/remote-3-dark-front-min.webp",
    "public/images/remote-3-dark-front-backlight.webp",
    "public/images/remote-3-dark-front-backlight-min.webp",
    "public/images/remote-3-dark-backlight-mask.png",
    "public/assets/ucvr-route-refresh.js",
    "public/assets/ucvr-sync-mode-pairing.js"
  ]) {
    if (!fs.existsSync(path.join(sourceDir, relative))) fail(`committed source is missing ${relative}`);
  }
}

function buildWithTemporaryEntry() {
  const indexPath = path.join(sourceDir, "index.html");
  const originalIndex = fs.readFileSync(indexPath, "utf8");
  const viteIndex = `<!doctype html>
<!-- Temporary Vite build entry generated by UC Virtual Remote. -->
<html lang="en">
  <head>
    <meta charset="UTF-8" />
    <meta name="viewport" content="width=device-width, initial-scale=1.0, maximum-scale=1.0, user-scalable=no" />
    <title>Web Configurator</title>
  </head>
  <body>
    <div id="app" class="app"></div>
    <script type="module" src="/src/main.ts"></script>
  </body>
</html>
`;
  fs.writeFileSync(indexPath, viteIndex);
  try {
    run("npm", ["run", "build"], sourceDir, { BASE_URL: "./" });
  } finally {
    fs.writeFileSync(indexPath, originalIndex);
  }
}

function injectSimulatorAssets(distDir) {
  const indexPath = path.join(distDir, "index.html");
  let index = fs.readFileSync(indexPath, "utf8");
  if (!index.includes("</head>") || !index.includes("</body>")) fail("built index.html is malformed");
  index = index.replace(
    "</head>",
    '<link rel="stylesheet" href="./assets/unfolded-simulator-source-integration.css"><script src="./assets/unfolded-simulator-bootstrap.js"></script></head>'
  );
  index = index.replace(
    "</body>",
    [
      '<script type="module" src="./assets/ucvr-simulator.js"></script>',
      '<script src="./assets/ucvr-route-refresh.js"></script>',
      '<script src="./assets/ucvr-sync-mode-pairing.js"></script>',
      "</body>"
    ].join("")
  );
  fs.writeFileSync(indexPath, index);
}

function validateBuild(distDir) {
  for (const relative of [
    "index.html",
    "VERSION",
    "release.json",
    "LICENSE",
    "MODIFICATIONS.md",
    "ARTWORK.md",
    "licenses.md",
    "LICENSES/CC-BY-4.0.txt",
    "logo.svg",
    "images/remote-3-dark-front.webp",
    "images/remote-3-dark-front-min.webp",
    "images/remote-3-dark-front-backlight.webp",
    "images/remote-3-dark-front-backlight-min.webp",
    "images/remote-3-dark-backlight-mask.png",
    "assets/unfolded-simulator-bootstrap.js",
    "assets/unfolded-simulator-source-integration.css",
    "assets/ucvr-simulator.js",
    "assets/ucvr-route-refresh.js",
    "assets/ucvr-sync-mode-pairing.js"
  ]) {
    if (!fs.existsSync(path.join(distDir, relative))) fail(`source build is missing ${relative}`);
  }
  if (fs.existsSync(path.join(distDir, "logo-dark.svg"))) fail("official logo-dark.svg must not be distributed");
  const release = JSON.parse(fs.readFileSync(path.join(distDir, "release.json"), "utf8"));
  if (release.version !== VERSION) fail(`release.json reports ${release.version || "no version"}`);
  const index = fs.readFileSync(path.join(distDir, "index.html"), "utf8");
  for (const asset of [
    "unfolded-simulator-bootstrap.js",
    "unfolded-simulator-source-integration.css",
    "ucvr-simulator.js",
    "ucvr-route-refresh.js",
    "ucvr-sync-mode-pairing.js"
  ]) {
    if (!index.includes(`./assets/${asset}`)) fail(`simulator asset is missing from index.html: ${asset}`);
  }
}

async function createCorrespondingSource(destination) {
  const temporary = await fsp.mkdtemp(path.join(os.tmpdir(), "ucvr-source-archive-"));
  const temporaryArchive = path.join(temporary, SOURCE_ARCHIVE_NAME);
  try {
    run("tar", [
      "--sort=name",
      "--mtime=@0",
      "--owner=0",
      "--group=0",
      "--numeric-owner",
      "--exclude=./node_modules",
      "--exclude=./dist",
      "--transform",
      `s,^\\./,${SOURCE_DIRECTORY_NAME}/,`,
      "-czf",
      temporaryArchive,
      "-C",
      sourceDir,
      "."
    ], root);
    await fsp.mkdir(path.dirname(destination), { recursive: true });
    await fsp.copyFile(temporaryArchive, destination);
  } finally {
    await fsp.rm(temporary, { recursive: true, force: true });
  }
}

const sourceAvailable = fs.existsSync(path.join(sourceDir, "package.json"));
if (!sourceAvailable) {
  if (!force && fs.existsSync(path.join(outputDir, "index.html")) && fs.existsSync(sourceArchive)) {
    console.log(`[web-configurator] ${VERSION} is already bundled in this installation`);
    process.exit(0);
  }
  fail(`committed Web Configurator source is unavailable at ${sourceDir}`);
}

validateSource();
const sourceDigest = sourceTreeSha256();
const prepared = !force
  && fs.existsSync(path.join(outputDir, "index.html"))
  && fs.existsSync(sourceArchive)
  && fs.existsSync(markerFile)
  && fs.readFileSync(markerFile, "utf8").trim() === sourceDigest;

if (prepared) {
  console.log(`[web-configurator] ${VERSION} is already built from the committed source tree`);
  process.exit(0);
}

run("npm", ["ci"], sourceDir);
await fsp.rm(path.join(sourceDir, "dist"), { recursive: true, force: true });
buildWithTemporaryEntry();
const distDir = path.join(sourceDir, "dist");
injectSimulatorAssets(distDir);
validateBuild(distDir);

await fsp.rm(outputDir, { recursive: true, force: true });
await fsp.cp(distDir, outputDir, { recursive: true });
await createCorrespondingSource(sourceArchive);
await fsp.writeFile(markerFile, `${sourceDigest}\n`);

console.log(`[web-configurator] Built ${VERSION} from ${sourceDir}`);
console.log(`[web-configurator] Runtime: ${outputDir}`);
console.log(`[web-configurator] Corresponding source: ${sourceArchive}`);
console.log(`[web-configurator] Corresponding source SHA-256: ${sha256(fs.readFileSync(sourceArchive))}`);
